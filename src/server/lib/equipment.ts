/**
 * Generate standard Fixed Asset Code (รหัสครุภัณฑ์ตามมาตรฐานกรมบัญชีกลาง)
 * Formula: [Class 4]-[Group 3]-[Item 4]-[FiscalYear 4]/[Serial 4]
 * Example: 6515-001-0001-2569/0001
 */
export function generateStandardAssetCode(
  classCode: string,
  groupCode: string,
  itemCode: string,
  fiscalYear: number | string,
  unitSequence: number
): string {
  const c = classCode.padStart(4, "0");
  const g = groupCode.padStart(3, "0");
  const i = itemCode.padStart(4, "0");
  const y = String(fiscalYear);
  const s = String(unitSequence).padStart(4, "0");
  return `${c}-${g}-${i}-${y}/${s}`;
}

/**
 * Calculate Straight-line Depreciation for Public Hospital Capital Assets
 * (คำนวณค่าเสื่อมราคาเส้นตรงตามระเบียบกระทรวงการคลัง: ราคาซาก 1 บาท)
 */
export function calculateEquipmentDepreciation(params: {
  acquisitionCost: number;
  usefulLifeYears: number;
  yearsInService: number;
}) {
  const { acquisitionCost, usefulLifeYears, yearsInService } = params;
  const salvageValue = 1; // ฿1.00 ตามระเบียบราชการ
  const depreciableBase = Math.max(0, acquisitionCost - salvageValue);
  const annualDepreciation = Number((depreciableBase / usefulLifeYears).toFixed(2));
  const effectiveYears = Math.min(usefulLifeYears, Math.max(0, yearsInService));
  const accumulatedDepreciation = Number((annualDepreciation * effectiveYears).toFixed(2));
  const netBookValue = Number(Math.max(salvageValue, acquisitionCost - accumulatedDepreciation).toFixed(2));

  return {
    acquisitionCost,
    salvageValue,
    usefulLifeYears,
    annualDepreciation,
    effectiveYears,
    accumulatedDepreciation,
    netBookValue,
    isFullyDepreciated: effectiveYears >= usefulLifeYears,
  };
}
